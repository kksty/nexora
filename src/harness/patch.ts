/**
 * Generate the profile patch that composes the harness for one executor.
 *
 * The patch keeps the mature harness's model loop, tools, compaction and
 * session persistence, removes capabilities that would create executors outside
 * the shared work table, and mounts the runtime's MCP tool bridge. It is
 * written once per task and reused by every work process.
 */

import { fileURLToPath } from 'node:url'
import type { TaskPaths } from '../core/paths.ts'
import { envModelMaxTokens, envModelThinking } from '../util/model-limits.ts'

function yamlString(value: string): string {
  return JSON.stringify(value)
}

/** The gate plugin lives beside this file and is loaded by absolute path. */
const LLM_CONCURRENCY_PLUGIN = fileURLToPath(new URL('./llm-concurrency.ts', import.meta.url))
/** Steering bridge for human commands; loaded beside the gate plugin. */
const COMMAND_STEER_PLUGIN = fileURLToPath(new URL('./command-steer.ts', import.meta.url))
const TERMINAL_ACTIVITY_PLUGIN = fileURLToPath(new URL('./terminal-activity.ts', import.meta.url))

export interface HarnessPatchOptions {
  paths: TaskPaths
  /** Absolute path to the MCP bridge entry file. */
  mcpEntry: string
  /** Absolute path to the node executable that runs the bridge. */
  nodeExecutable: string
}

/**
 * Upper bound for one model response.
 *
 * The SDK defaults this to the official DeepSeek ceiling (256000). Third-party
 * OpenAI/Anthropic-compatible gateways frequently cap it far lower, and at least
 * one of them answers an oversized `max_tokens` with an empty turn
 * (`output_tokens: 0`, no content blocks) instead of an error - which the
 * harness surfaces as EMPTY_RESPONSE, so the executor silently does nothing.
 * The effective value comes from the Web UI settings or LIEBIAN_MODEL_MAX_TOKENS;
 * see `src/util/model-limits.ts`.
 */

/** Render the YAML patch document. */
export function renderHarnessPatch(options: HarnessPatchOptions): string {
  const { paths, mcpEntry, nodeExecutable } = options
  return `# Generated by the liebian runtime for task ${paths.taskId}.
# Do not edit while the task is running.

# Session logs live with the task so that recovery does not depend on an
# unrelated harness home directory.
- id: session-persistence-jsonl
  config:
    root: ${yamlString(paths.sessionsDir)}
    compression: none

# Cap the per-response output budget. The provider default is the official
# DeepSeek ceiling; a gateway that caps lower may answer with an empty turn
# instead of an error, which reads as "the executor does nothing".
#
# Third-party gateways that emulate the Messages API also emit the occasional
# malformed stream (a block delta without its start). That is a transport-level
# glitch, not a model decision, so it is retried like the built-in transient
# codes instead of ending the turn.
- id: llm-deepseek
  config:
    maxTokens: ${envModelMaxTokens()}
    thinking: ${envModelThinking() === 'off' ? 'disabled' : 'enabled'}
    reasoningEffort: ${envModelThinking()}
    retryPolicy:
      mode: normal
      maxRetries: 5
      retryableCodes:
        - EMPTY_RESPONSE
        - RATE_LIMIT
        - SERVER
        - TIMEOUT
        - TRANSPORT
        - MALFORMED_RESPONSE

# Executors need to run arbitrary local security tooling. The container, not
# the per-Work process, is the isolation boundary.
- id: sandbox-policy
  config:
    mode: danger-full-access
    workspaceRoot: !!js process.cwd()

# Bash is the only shell in the executor environment. Keep one shell dialect so
# prompts, examples, evidence and recovery notes do not depend on the host OS.
- id: bash-sandbox
  disabled: false
  config:
    timeoutMs: 900000

- id: tool-bash
  disabled: false
  config:
    enableRunInBackground: true
    promoteOnTimeout: true

# Minimal model-facing tool surface. bash is the primary interface; the file
# tools exist only to make structured reads/edits reliable, and background jobs
# are how long-running CLI commands are polled. Everything else the base profile
# offers is deliberately absent:
#   - web_search / web_fetch: use curl/wget through bash.
#   - todo_write: the shared findings document is the task memory.
#   - working_directory: the task directory is fixed for the whole Work.
# (The sdk profile does not mount a present tool at all.)
- id: tool-fs
  config:
    read: true
    write: true
    edit: true
    readImage: false

- id: tool-web
  disabled: true

- id: tool-todo
  disabled: true

- id: tool-working-directory
  disabled: true

# No preinstalled skills, and no hidden delegation paths: a new executor must be
# registered in the shared work table and take part in consensus.
- id: skill-filesystem
  disabled: true

- id: tool-skill
  disabled: true

- id: tool-subagent
  disabled: true

- id: tool-subagent-fork
  disabled: true

- id: tool-subagent-control
  disabled: true

- id: tool-subagent-list-agents
  disabled: true

- id: tool-workflow
  disabled: true

- id: tool-goal
  disabled: true

# Every model stream takes one shared permit from the task runtime, so all
# executors together stay within LIEBIAN_MODEL_CONCURRENCY requests in flight.
# The permit is held only while the streamed response is open.
- insert:
    - id: terminal
      name: '@deepseek-ai/dsh-terminal'
    - id: terminal-bash
      name: '@deepseek-ai/dsh-terminal-bash'
      config:
        shellDialect: bash
        shellPath: /bin/bash
    - id: tool-terminal
      name: '@deepseek-ai/dsh-tool-terminal'
      config:
        enableRunInBackground: true
    - id: liebian-terminal-activity
      name: ${yamlString(TERMINAL_ACTIVITY_PLUGIN)}
    - id: llm-concurrency
      name: ${yamlString(LLM_CONCURRENCY_PLUGIN)}
    - id: command-steer
      name: ${yamlString(COMMAND_STEER_PLUGIN)}
    - id: mcp-liebian
      name: '@deepseek-ai/dsh-mcp-client'
      config:
        serverName: liebian
        transport: stdio
        command: ${yamlString(nodeExecutable)}
        args:
          - ${yamlString(mcpEntry)}
        cwd: ${yamlString(paths.taskDir)}
        env:
          LIEBIAN_DAEMON_URL: !!js process.env.LIEBIAN_DAEMON_URL
          LIEBIAN_DAEMON_TOKEN: !!js process.env.LIEBIAN_DAEMON_TOKEN
          LIEBIAN_WORK: !!js process.env.LIEBIAN_WORK
        toolCallTimeoutMs: 900000
        failOnStartupError: true
`
}
